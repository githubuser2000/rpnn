use serde::Serialize;

use crate::schema::ParameterMatrixEntry;

#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize)]
pub struct ParameterBucketProjection {
    pub bucket: u8,
    pub integers: &'static [i64],
    pub symbols: &'static [&'static str],
}

#[derive(Clone, Debug, Eq, PartialEq, Serialize)]
pub struct OwnedParameterBucketProjection {
    pub bucket: u8,
    pub integers: Vec<i64>,
    pub symbols: Vec<String>,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq, Serialize)]
pub struct ParameterMatrixSeed {
    pub source_index: usize,
    pub main_aliases: &'static [&'static str],
    pub parameter_aliases: &'static [&'static str],
    pub columns: &'static [i64],
    pub buckets: &'static [ParameterBucketProjection],
    pub legacy_bucket_count: usize,
}

impl ParameterMatrixSeed {
    pub fn to_entry(self) -> ParameterMatrixEntry {
        ParameterMatrixEntry {
            main_aliases: self
                .main_aliases
                .iter()
                .map(|value| (*value).to_string())
                .collect(),
            parameter_aliases: self
                .parameter_aliases
                .iter()
                .map(|value| (*value).to_string())
                .collect(),
            columns: self.columns.to_vec(),
        }
    }
}


pub const PARAMETER_MATRIX_SYMBOL_COUNT: usize = 32;
pub const PARAMETER_MATRIX_NONEMPTY_BUCKET_PROJECTION_COUNT: usize = 441;

pub fn parameter_matrix_entries() -> Vec<ParameterMatrixEntry> {
    PARAMETER_MATRIX_SEEDS
        .iter()
        .copied()
        .map(ParameterMatrixSeed::to_entry)
        .collect()
}

pub fn parameter_matrix_seed_count() -> usize {
    PARAMETER_MATRIX_SEEDS.len()
}

pub fn integer_column_projection_count() -> usize {
    let mut seen = std::collections::BTreeSet::new();
    for seed in PARAMETER_MATRIX_SEEDS {
        for column in seed.columns {
            seen.insert(*column);
        }
    }
    seen.len()
}

pub fn symbolic_bucket_projection_count() -> usize {
    PARAMETER_MATRIX_SYMBOL_COUNT
}

pub fn nonempty_bucket_projection_count() -> usize {
    PARAMETER_MATRIX_NONEMPTY_BUCKET_PROJECTION_COUNT
}

pub fn columns_for_alias_pair(main: &str, parameter: &str) -> Vec<i64> {
    let mut out = std::collections::BTreeSet::new();
    let main = main.trim();
    let parameter = parameter.trim();
    for seed in PARAMETER_MATRIX_SEEDS {
        if seed.main_aliases.iter().any(|alias| *alias == main)
            && seed
                .parameter_aliases
                .iter()
                .any(|alias| *alias == parameter)
        {
            out.extend(seed.columns.iter().copied());
        }
    }
    out.into_iter().collect()
}

pub fn bucket_projections_for_alias_pair(
    main: &str,
    parameter: &str,
) -> Vec<OwnedParameterBucketProjection> {
    let mut integers_by_bucket: std::collections::BTreeMap<u8, std::collections::BTreeSet<i64>> =
        std::collections::BTreeMap::new();
    let mut symbols_by_bucket: std::collections::BTreeMap<u8, std::collections::BTreeSet<String>> =
        std::collections::BTreeMap::new();
    let main = main.trim();
    let parameter = parameter.trim();
    for seed in PARAMETER_MATRIX_SEEDS {
        if seed.main_aliases.iter().any(|alias| *alias == main)
            && seed
                .parameter_aliases
                .iter()
                .any(|alias| *alias == parameter)
        {
            for projection in seed.buckets {
                integers_by_bucket
                    .entry(projection.bucket)
                    .or_default()
                    .extend(projection.integers.iter().copied());
                symbols_by_bucket
                    .entry(projection.bucket)
                    .or_default()
                    .extend(projection.symbols.iter().map(|value| (*value).to_string()));
            }
        }
    }
    let mut keys = integers_by_bucket
        .keys()
        .copied()
        .collect::<std::collections::BTreeSet<_>>();
    keys.extend(symbols_by_bucket.keys().copied());
    keys.into_iter()
        .map(|bucket| OwnedParameterBucketProjection {
            bucket,
            integers: integers_by_bucket
                .remove(&bucket)
                .unwrap_or_default()
                .into_iter()
                .collect(),
            symbols: symbols_by_bucket
                .remove(&bucket)
                .unwrap_or_default()
                .into_iter()
                .collect(),
        })
        .collect()
}

pub fn canonical_pair_for_aliases(main: &str, parameter: &str) -> Option<(String, String)> {
    let main = main.trim();
    let parameter = parameter.trim();
    PARAMETER_MATRIX_SEEDS.iter().find_map(|seed| {
        if seed.main_aliases.iter().any(|alias| *alias == main)
            && seed
                .parameter_aliases
                .iter()
                .any(|alias| *alias == parameter)
        {
            Some((
                seed.main_aliases[0].to_string(),
                seed.parameter_aliases[0].to_string(),
            ))
        } else {
            None
        }
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generated_matrix_contains_current_744_regression() {
        let columns = columns_for_alias_pair("kontinuum", "m");
        assert!(columns.contains(&493));
        assert!(columns.contains(&744));
        let buckets = bucket_projections_for_alias_pair("kontinuum", "m");
        assert_eq!(
            buckets
                .iter()
                .find(|item| item.bucket == 0)
                .unwrap()
                .integers,
            vec![493, 744]
        );
        assert_eq!(
            canonical_pair_for_aliases("kontinuum", "m"),
            Some(("Kontinuum".to_string(), "M".to_string()))
        );
    }

    #[test]
    fn generated_matrix_preserves_symbolic_bucket_payloads() {
        let buckets = bucket_projections_for_alias_pair("multiplikationen", "motivstern");
        let bucket = buckets.iter().find(|item| item.bucket == 7).unwrap();
        assert_eq!(bucket.symbols, vec!["primMotivStern".to_string()]);
        let gebrochen = bucket_projections_for_alias_pair("gebrochenuniversum", "2");
        assert!(gebrochen
            .iter()
            .any(|item| item.bucket == 5 && item.symbols.contains(&"2".to_string())));
    }

    #[test]
    fn generated_matrix_is_not_empty() {
        assert!(parameter_matrix_seed_count() >= 400);
        assert!(integer_column_projection_count() >= 600);
        assert!(symbolic_bucket_projection_count() >= 30);
        assert!(nonempty_bucket_projection_count() >= parameter_matrix_seed_count());
    }
}
